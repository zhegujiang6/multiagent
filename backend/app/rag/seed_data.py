async def seed_all() -> None:
    faqs = get_faq_entries()
    sops = get_sop_entries()

    article_ids = []
    print("Persisting canonical knowledge assets in PostgreSQL...")
    for entry in faqs:
        article = await create_knowledge_article(
            title=entry["title"],
            content=entry["content"],
            category=entry.get("category", "faq"),
            tags=entry.get("tags", []),
            status="approved",
            canonical_key=f"seed:{entry['id']}",
            source_type="seed_faq",
            owner="knowledge_seed",
            meta_info={"seed_id": entry["id"]},
        )
        article_ids.append(article.id)

    for entry in sops:
        article = await create_knowledge_article(
            title=entry["title"],
            content=entry["content"],
            category=entry.get("category", "SOP"),
            tags=entry.get("tags", []),
            status="approved",
            canonical_key=f"seed:{entry['id']}",
            source_type="seed_sop",
            owner="knowledge_seed",
            meta_info={"seed_id": entry["id"]},
        )
        article_ids.append(article.id)

    print("Rebuilding FAQ and SOP vector indexes...")
    recreate_collection(FAQ_COLLECTION)
    recreate_collection(SOP_COLLECTION)
    await publish_articles(article_ids)
    print(f"  [OK] {len(faqs)} FAQ entries loaded")
    print(f"  [OK] {len(sops)} SOP entries loaded")

    print("Done! Vector store is ready.")


if __name__ == "__main__":
    asyncio.run(seed_all())
